"""One isolated worker. All competitor imports happen inside adapter()."""

from __future__ import annotations

import argparse
import gc
import hashlib
import importlib
import importlib.metadata
import json
import sys
from collections.abc import Callable
from pathlib import Path
from time import perf_counter_ns
from typing import Any, TypedDict, cast

ROOT = Path(__file__).resolve().parents[2]
CORPUS = ROOT / "tests/fixtures/real"
ADAPTERS = {
    "htomd": ("htomd", "convert", "htomd.convert(html)"),
    "markdownify": ("markdownify", "markdownify", "markdownify.markdownify(html)"),
    "html2text": ("html2text", "html2text", "html2text.html2text(html)"),
    "trafilatura": (
        "trafilatura",
        "extract",
        "trafilatura.extract(html, output_format='markdown')",
    ),
    "html-to-markdown": ("html_to_markdown", "convert", "html_to_markdown.convert(html).content"),
    "htmd-py": ("htmd", "convert_html", "htmd.convert_html(html)"),
}
SMOKE_HTML = (
    "<html><body><article><h1>Benchmark tea</h1>"
    + "<p>Steep the tea and enjoy a readable paragraph. "
    + "A warm cup of tea takes time to prepare, with fresh water and fragrant leaves. " * 20
    + "</p></article></body></html>"
)


class Document(TypedDict):
    id: str
    sha256: str
    bytes: int
    encoding: str


class Output(TypedDict):
    id: str
    characters: int
    empty: bool
    error: str | None


class Worker(TypedDict, total=False):
    error: str
    stderr: str
    corpus_ns: list[int]
    document_ns: dict[str, list[int]]
    outputs: list[Output]
    output_passes: list[list[Output]]
    rss_bytes: int
    import_ns: int
    packages: dict[str, str]
    installed_bytes: int
    wheel_tags: list[str]
    smoke: str


def adapter(name: str) -> Callable[[str], str | None]:
    module, function, _ = ADAPTERS[name]
    convert = cast(Callable[..., Any], getattr(importlib.import_module(module), function))
    if name == "trafilatura":
        return lambda html: cast(str | None, convert(html, output_format="markdown"))
    if name == "html-to-markdown":
        return lambda html: cast(str, convert(html).content)
    return cast(Callable[[str], str | None], convert)


def load_corpus() -> tuple[list[Document], list[str]]:
    manifest = json.loads((CORPUS / "manifest.json").read_text(encoding="utf-8"))
    documents: list[Document] = []
    inputs: list[str] = []
    for item in sorted(manifest, key=lambda row: row["id"]):
        raw = (CORPUS / f"{item['id']}.html").read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        if digest != item["sha256"]:
            raise ValueError(f"Snapshot hash mismatch: {item['id']}")
        documents.append(
            Document(id=item["id"], sha256=digest, bytes=len(raw), encoding=item["encoding"])
        )
        inputs.append(raw.decode(item["encoding"]))
    if len(documents) != 115:
        raise ValueError(f"Expected 115 snapshots, found {len(documents)}")
    return documents, inputs


def rss_bytes(value: int, platform: str) -> int:
    if platform == "darwin":
        return value
    if platform.startswith("linux"):
        return value * 1024
    raise ValueError(f"Unsupported RSS platform: {platform}")


def footprint(paths: list[Path]) -> int:
    """Logical file bytes owned by packages, without generated bytecode."""
    return sum(
        path.stat().st_size
        for path in set(paths)
        if path.is_file()
        and not path.is_symlink()
        and "__pycache__" not in path.parts
        and path.suffix not in {".pyc", ".pyo"}
    )


def installation(name: str) -> Worker:
    packages: dict[str, str] = {}
    paths: list[Path] = []
    for dist in importlib.metadata.distributions():
        package = dist.metadata["Name"]
        if package.lower() in {"pip", "setuptools", "wheel"}:
            continue
        packages[package] = dist.version
        paths.extend(Path(str(dist.locate_file(file))) for file in dist.files or [])
    wheel = importlib.metadata.distribution(name).read_text("WHEEL") or ""
    return Worker(
        packages=packages,
        installed_bytes=footprint(paths),
        wheel_tags=[line[5:] for line in wheel.splitlines() if line.startswith("Tag: ")],
    )


def corpus_pass(
    convert: Callable[[str], str | None],
    documents: list[Document],
    inputs: list[str],
) -> tuple[list[int], list[Output]]:
    timings: list[int] = []
    outputs: list[Output] = []
    for document, html in zip(documents, inputs, strict=True):
        error = None
        result: str | None = None
        start = perf_counter_ns()
        try:
            result = convert(html)
        except Exception as exc:
            elapsed = perf_counter_ns() - start
            error = f"{type(exc).__name__}: {exc}"
        else:
            elapsed = perf_counter_ns() - start
        # Validation, output lengths and bookkeeping are outside the timed section.
        if result is not None and not isinstance(result, str):
            error = f"Unexpected return type: {type(result).__name__}"
            result = None
        timings.append(elapsed)
        outputs.append(
            Output(id=document["id"], characters=len(result or ""), empty=not result, error=error)
        )
    return timings, outputs


def measure(name: str, mode: str, passes: int, seconds: float) -> Worker:
    if mode == "installation":
        return installation(name)
    convert = adapter(name)
    if mode == "smoke":
        smoke = convert(SMOKE_HTML)
        if not isinstance(smoke, str) or "Steep the tea" not in smoke:
            raise ValueError(f"Adapter smoke failed: {smoke!r}")
        return Worker(smoke=smoke)
    documents, inputs = load_corpus()
    gc.enable()
    _, outputs = corpus_pass(convert, documents, inputs)  # One warm-up corpus pass.
    if mode == "rss":
        import resource

        # No timing history retained in the memory worker.
        return Worker(
            outputs=outputs,
            rss_bytes=rss_bytes(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss, sys.platform),
        )
    result = Worker(
        corpus_ns=[],
        document_ns={d["id"]: [] for d in documents},
        outputs=outputs,
        output_passes=[outputs],
    )
    total = 0
    while len(result["corpus_ns"]) < passes or total < seconds * 1e9:
        timings, outputs = corpus_pass(convert, documents, inputs)
        duration = sum(timings)
        result["corpus_ns"].append(duration)
        total += duration
        result["output_passes"].append(outputs)
        for document, elapsed in zip(documents, timings, strict=True):
            result["document_ns"][document["id"]].append(elapsed)
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("name", choices=ADAPTERS)
    parser.add_argument("mode", choices=["installation", "smoke", "speed", "rss"])
    parser.add_argument("output", type=Path)
    parser.add_argument("--passes", type=int, default=5)
    parser.add_argument("--seconds", type=float, default=2)
    args = parser.parse_args()
    try:
        result = measure(args.name, args.mode, args.passes, args.seconds)
    except Exception as exc:
        result = Worker(error=f"{type(exc).__name__}: {exc}")
    args.output.write_text(json.dumps(result), encoding="utf-8")


if __name__ == "__main__":
    main()
